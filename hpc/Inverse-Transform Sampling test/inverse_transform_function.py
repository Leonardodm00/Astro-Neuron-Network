# =============================================================================
# 2. THE TWO SAMPLERS  (python fallback + cython + cpp registrations)
# =============================================================================
# --- FORMER: Bernoulli-sum loop (original). n rand() draws, returns int. ------
FORMER_CPP = r'''
int Binomial_fun(int n, double p, int _vectorisation_idx) {
    int count = 0;
    for (int i = 0; i < n; ++i) {
        if (rand(_vectorisation_idx) < p) count += 1;   // n rand() per call
    }
    return count;
}
'''
FORMER_CYTHON = r'''
cdef double Binomial_fun(int n, double p, _vectorisation_idx):
    cdef int count = 0
    cdef int i
    for i in range(n):
        if rand(_vectorisation_idx) < p:
            count = count + 1
    return count
'''
def _former_py(n, p, _vi):
    return int(np.sum(np.random.rand(int(n)) < p))


# --- BINV: inverse-transform on the Binomial CDF (new). ONE rand(), double. ---
# Walk the pmf recurrence  pmf_{k+1} = pmf_k * (n-k)/(k+1) * p/(1-p),
# accumulating the cdf, and return the first k whose cdf exceeds U ~ Uniform(0,1).
# q^n is built with a short loop (n <= 5) so no <cmath>/pow is pulled in.
BINV_CPP = r'''
double Binomial_fun(int n, double p, int _vectorisation_idx) {
    if (n <= 0 || p <= 0.0) return 0.0;
    if (p >= 1.0) return (double)n;
    double q = 1.0 - p;
    double r = p / q;
    double pmf = 1.0;
    for (int i = 0; i < n; ++i) pmf *= q;       // q^n
    double cdf = pmf;
    double U = rand(_vectorisation_idx);         // exactly ONE draw
    int k = 0;
    while (U > cdf && k < n) {
        k += 1;
        pmf *= ((double)(n - k + 1) / (double)k) * r;
        cdf += pmf;
    }
    return (double)k;
}
'''
BINV_CYTHON = r'''
cdef double Binomial_fun(int n, double p, _vectorisation_idx):
    cdef double q, r, pmf, cdf, U
    cdef int k, i
    if n <= 0 or p <= 0.0:
        return 0.0
    if p >= 1.0:
        return <double>n
    q = 1.0 - p
    r = p / q
    pmf = 1.0
    for i in range(n):
        pmf = pmf * q
    cdf = pmf
    U = rand(_vectorisation_idx)
    k = 0
    while U > cdf and k < n:
        k = k + 1
        pmf = pmf * (<double>(n - k + 1) / <double>k) * r
        cdf = cdf + pmf
    return <double>k
'''
def _binv_py(n, p, _vi):
    n = int(n)
    if n <= 0 or p <= 0.0:
        return 0
    if p >= 1.0:
        return n
    q = 1.0 - p; r = p / q; pmf = q ** n; cdf = pmf; U = np.random.rand(); k = 0
    while U > cdf and k < n:
        k += 1; pmf *= ((n - k + 1) / k) * r; cdf += pmf
    return k


def make_binomial_fun(kind):
    """Build a Brian2 Function 'Binomial_fun' for the chosen sampler.

    kind : 'former' or 'binv'. Registers python (fallback) + cython + cpp,
    so the same object works for target='numpy'/'cython'/'cpp_standalone'.
    """
    from brian2 import Function, DEFAULT_FUNCTIONS
    if kind == 'former':
        py, cy, cpp = _former_py, FORMER_CYTHON, FORMER_CPP
    elif kind == 'binv':
        py, cy, cpp = _binv_py, BINV_CYTHON, BINV_CPP
    else:
        raise ValueError(f"kind must be 'former' or 'binv', got {kind!r}")
    fun = Function(py, arg_units=[1, 1], return_unit=1,
                   stateless=False, auto_vectorise=True)
    dep = {'rand': DEFAULT_FUNCTIONS['rand']}
    fun.implementations.add_implementation('cython', cy, dependencies=dep)
    fun.implementations.add_implementation('cpp',    cpp, dependencies=dep)
    return fun


def _fresh_cpp_device(build_dir):
    """Activate a clean cpp_standalone device (needed between sequential runs)."""
    from brian2 import set_device, get_device
    set_device('cpp_standalone', directory=build_dir, build_on_run=True)
    get_device().reinit()
    get_device().activate(build_on_run=True, directory=build_dir)


