def _in_notebook():
    """True when running inside an IPython/Jupyter/Colab kernel."""
    try:
        from IPython import get_ipython
        ip = get_ipython()
        return ip is not None and ip.__class__.__name__ != 'TerminalInteractiveShell'
    except Exception:
        return False


def main(argv=None):
    # In Colab/Jupyter, sys.argv carries the kernel's own flags
    # (e.g. "-f .../kernel.json"); ignore them and use defaults there.
    if argv is None:
        argv = [] if _in_notebook() else sys.argv[1:]

    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--Nsyn', type=int, default=200, help='synapses in PART B')
    ap.add_argument('--T',    type=float, default=5.0, help='sim time [s] in PART B')
    ap.add_argument('--M',    type=int, default=20000, help='samples/cell in PART A')
    ap.add_argument('--seed', type=int, default=1234)
    ap.add_argument('--skipA', action='store_true', help='skip the sampler unit test')
    ap.add_argument('--skipB', action='store_true', help='skip the network test')
    ap.add_argument('--noplot', action='store_true')
    args, _unknown = ap.parse_known_args(argv)
    P = PARAMS

    print("=" * 70)
    print("async-release on cpp_standalone | FORMER vs BINV Binomial samplers")
    print(f"x0={P['x0']}  n_max={int(1/P['x0'])}  Omega_c={P['Omega_c']}Hz "
          f"(tau_clear={1e3/P['Omega_c']:.1f} ms)  rho={P['rho']}  "
          f"Y_T={P['Y_T_mmole']} mmole")
    print(f"dt={P['dt_ms']} ms  rate={P['rate_hz']} Hz  "
          f"PART A M={args.M}  PART B Nsyn={args.Nsyn} T={args.T}s  seed={args.seed}")
    print("=" * 70)

    okA = True
    if not args.skipA:
        okA_f = sampler_check('former', P, args.M, args.seed, '/tmp/sampA_former')
        okA_b = sampler_check('binv',   P, args.M, args.seed, '/tmp/sampA_binv')
        okA = okA_f and okA_b

    okB = True
    rF = rB = None
    if not args.skipB:
        dt_s = P['dt_ms'] * 1e-3
        drive = make_poisson_drive(args.Nsyn, args.T, P['rate_hz'], dt_s, args.seed)
        print(f"\n[drive] Nsyn={args.Nsyn}  total presyn spikes={drive[0].size}")
        rF = run_async_network('former', drive, P, args.Nsyn, args.T,
                               args.seed, '/tmp/netB_former')
        rB = run_async_network('binv',   drive, P, args.Nsyn, args.T,
                               args.seed, '/tmp/netB_binv')
        okB = compare_ensembles(rF, rB, args.Nsyn)
        if not args.noplot:
            make_plots(rF, rB)

    print("\n" + "=" * 70)
    print(f"OVERALL: PART A {'PASS' if okA else 'FAIL'} | "
          f"PART B {'PASS' if okB else 'FAIL'} | "
          f"{'ALL PASS' if (okA and okB) else 'SOME FAILED'}")
    print("=" * 70)
    return 0 if (okA and okB) else 1


if __name__ == '__main__':
    _rc = main()
    if not _in_notebook():
        raise SystemExit(_rc)