# Minimal, self-contained reproduction of the ASYNCHRONOUS-RELEASE synapse
# model on the Brian2 `cpp_standalone` backend, run with BOTH Binomial
# samplers so they can be compared head-to-head on the real C++ code path:
#
#     FORMER  -- Bernoulli-sum loop:  k = sum_{i=1..n} 1[rand() < p]
#                (n rand() draws per call; returns int)   <- the original
#     BINV    -- inverse-transform sampling on the Binomial CDF
#                (exactly ONE rand() draw per call; returns double) <- the new one
#
# Both are EXACT samplers of Binomial(n, p); they differ only in algorithm and
# in how many uniform draws they consume. This script demonstrates, on the
# compiled standalone binary, that:
#   (A) at the sampler level, each reproduces scipy.stats.binom(n, p);
#   (B) at the network level, the two produce statistically indistinguishable
#       ensemble distributions of the history-integrating observables
#       C_async(T) and  integral_0^T Y_S(t) dt.
#
