def make_plots(rF, rB, out_png="async_release_cpp.png"):
    fig, ax = plt.subplots(1, 3, figsize=(15, 4.2))
    # (a) C_async(T) histograms
    bins = np.histogram_bin_edges(np.concatenate([rF['C'], rB['C']]), bins=30)
    ax[0].hist(rF['C'], bins=bins, alpha=0.55, label='FORMER', color='#1f4e79')
    ax[0].hist(rB['C'], bins=bins, alpha=0.55, label='BINV',   color='#c0504d')
    ax[0].set_xlabel(r'$C_\mathrm{async}(T)$  (cumulative released NT)')
    ax[0].set_ylabel('synapse count'); ax[0].set_title('(a) cumulative async release')
    ax[0].legend(frameon=False)
    # (b) int Y_S dt histograms
    bins = np.histogram_bin_edges(np.concatenate([rF['YSint'], rB['YSint']]), bins=30)
    ax[1].hist(rF['YSint'], bins=bins, alpha=0.55, label='FORMER', color='#1f4e79')
    ax[1].hist(rB['YSint'], bins=bins, alpha=0.55, label='BINV',   color='#c0504d')
    ax[1].set_xlabel(r'$\int_0^T Y_S\,dt$  (mole$\cdot$s)')
    ax[1].set_ylabel('synapse count'); ax[1].set_title('(b) cleft-glutamate exposure')
    ax[1].legend(frameon=False)
    # (c) example Y_S(t) traces
    for k in range(min(3, rB['YS_tr'].shape[0])):
        ax[2].plot(rB['tgrid'], rB['YS_tr'][k], lw=0.8)
    ax[2].set_xlabel('time (s)'); ax[2].set_ylabel(r'$Y_S$ (mmole)')
    ax[2].set_title(r'(c) example $Y_S(t)$ traces (BINV)')
    fig.tight_layout()
    fig.savefig(out_png, dpi=130)
    print(f"\n[plot] saved -> {out_png}")
    try:
        plt.show()
    except Exception:
        pass


