def nominal_grid(P):
    """The (n, p) grid the production smoke test uses."""
    n_max = int(np.floor(1.0 / P['x0']))                 # 5
    p_max = P['Umax'] * (P['dt_ms'] * 1e-3)              # 0.025
    ns = sorted(set(max(1, int(round(v))) for v in np.linspace(1, n_max, 4)))
    ps = [p_max / 50.0, p_max / 10.0, p_max / 2.0, p_max]
    return [(n, float(p)) for n in ns for p in ps]


def sampler_check(kind, P, M, seed, build_dir):
    """Draw M samples per (n,p) cell on cpp_standalone; KS/moment-test vs scipy."""
    from brian2 import (start_scope, NeuronGroup, StateMonitor, run,
                        defaultclock, ms, seed as bseed)
    _fresh_cpp_device(build_dir)
    start_scope()
    defaultclock.dt = P['dt_ms'] * ms

    fun = make_binomial_fun(kind)
    grid = nominal_grid(P)
    n_arr = np.array([g[0] for g in grid], float)
    p_arr = np.array([g[1] for g in grid], float)

    G = NeuronGroup(
        len(grid),
        '''n_cell : 1 (constant)
           p_cell : 1 (constant)
           k = Binomial_fun(int(n_cell), p_cell) : 1 (constant over dt)''',
        namespace={'Binomial_fun': fun},
    )
    G.n_cell = n_arr; G.p_cell = p_arr
    mon = StateMonitor(G, 'k', record=True, dt=P['dt_ms'] * ms)
    bseed(seed)
    run(M * P['dt_ms'] * ms)                              # M steps -> M samples/cell
    K = np.asarray(mon.k)                                 # (ncells, ~M)

    print(f"\n--- PART A: {kind.upper()} sampler on cpp_standalone "
          f"(M={K.shape[1]}/cell) ---")
    print(f"{'n':>2} {'p':>9} | {'np':>7} {'mean':>8} | {'npq':>7} {'var':>8}"
          f" | {'var/npq':>7} | {'KS_p':>8}  res")
    all_ok = True
    for c, (n, p) in enumerate(grid):
        s = K[c]; q = 1.0 - p
        mean_th, var_th = n * p, n * p * q
        ref = stats.binom.rvs(n, p, size=s.size, random_state=seed + c)
        ks, pv = stats.ks_2samp(s, ref)
        ratio = s.var() / var_th if var_th > 0 else np.nan
        ok = pv > 1e-4
        all_ok &= ok
        print(f"{n:>2} {p:>9.2e} | {mean_th:>7.4f} {s.mean():>8.4f} | "
              f"{var_th:>7.4f} {s.var():>8.4f} | {ratio:>7.2f} | "
              f"{pv:>8.2g}  {'OK' if ok else 'FAIL'}")
    print(f"PART A {kind.upper()}: {'PASS' if all_ok else 'FAIL'}")
    return all_ok


