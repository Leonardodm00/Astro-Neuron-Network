def make_poisson_drive(Nsyn, T_s, rate_hz, dt_s, seed):
    """Pre-generate per-synapse Poisson spike trains on the dt grid.

    Returned once and reused for BOTH samplers, so the drive is byte-identical
    across runs and the only difference is the Binomial algorithm itself.
    """
    rng = np.random.default_rng(seed)
    nsteps = int(round(T_s / dt_s))
    idx, t = [], []
    for j in range(Nsyn):
        hits = np.nonzero(rng.random(nsteps) < rate_hz * dt_s)[0]
        idx.append(np.full(hits.size, j)); t.append(hits * dt_s)
    idx = np.concatenate(idx); t = np.concatenate(t)
    order = np.argsort(t, kind='stable')                 # SpikeGeneratorGroup wants sorted t
    return idx[order], t[order]


def run_async_network(kind, drive, P, Nsyn, T_s, seed, build_dir, n_trace=6):
    """Build + run the async-release synapse model on cpp_standalone.

    Observables (both integrate history, hence endpoint-robust):
      C_async(T)  -- cumulative async-released NT (dimensionless)
      YS_int(T)   -- integral_0^T Y_S dt          (mole*second), in-equation integrator
    A few Y_S(t) traces are also recorded for plotting and as an integrator cross-check.
    """
    from brian2 import (start_scope, NeuronGroup, Synapses, SpikeGeneratorGroup,
                        StateMonitor, run, defaultclock, ms, second, Hz,
                        mmole, mole, seed as bseed)
    spk_i, spk_t = drive
    _fresh_cpp_device(build_dir)
    start_scope()
    defaultclock.dt = P['dt_ms'] * ms

    Binomial_fun = make_binomial_fun(kind)
    ns = {'Omega_c': P['Omega_c'] / second, 'rho': P['rho'],
          'Binomial_fun': Binomial_fun}

    # ---- async + synchronous release + fast cleft Y_S (library equations) ----
    eqs = '''
    dx_S/dt = Omega_d*(1 - x_S) - r_Ar                    : 1    (clock-driven)
    r_Ar    = x0*nar                                       : Hz
    nar     = Binomial_fun(int(floor(x_S/x0)), uar*dt)/dt : Hz   (constant over dt)
    duar/dt = -uar*Omega_f_ar                             : Hz   (clock-driven)
    dusr/dt = -Omega_f_sr*usr                             : 1    (clock-driven)
    r_Sr : 1
    dY_S/dt     = -Omega_c*Y_S + rho*Y_T*r_Ar             : mole (clock-driven)
    dC_async/dt = r_Ar                                    : 1    (clock-driven)
    dYS_int/dt  = Y_S                                     : mole*second (clock-driven)
    Omega_d : 1/second
    Omega_f_ar : 1/second
    Omega_f_sr : 1/second
    U_0_ar : 1
    U_0_sr : 1
    Umax : 1/second
    x0 : 1
    Y_T : mole
    '''
    on_pre = '''
    usr += U_0_sr*(1 - usr)
    r_Sr = usr*x_S
    x_S -= r_Sr
    uar += U_0_ar*(Umax - uar)
    Y_S += rho*Y_T*r_Sr
    '''
    P_in = SpikeGeneratorGroup(Nsyn, spk_i, spk_t * second)
    post = NeuronGroup(Nsyn, 'dummy : 1')
    S = Synapses(P_in, post, model=eqs, on_pre=on_pre, namespace=ns, method='euler')
    S.connect(j='i')                                      # one synapse per drive line

    # initial conditions + per-synapse parameters (library nominal)
    S.x_S = 1.0; S.usr = 0.0; S.uar = 0.0 * Hz; S.Y_S = 0.0 * mmole
    S.C_async = 0.0; S.YS_int = 0.0 * mole * second
    S.Omega_d    = P['Omega_d']    / second
    S.Omega_f_ar = P['Omega_f_ar'] / second
    S.Omega_f_sr = P['Omega_f_sr'] / second
    S.U_0_ar = P['U_0_ar']; S.U_0_sr = P['U_0_sr']
    S.Umax = P['Umax'] / second
    S.x0 = P['x0']; S.Y_T = P['Y_T_mmole'] * mmole

    # record a few synapses' Y_S(t) for plotting + integrator cross-check
    rec = np.arange(min(n_trace, Nsyn))
    monYS = StateMonitor(S, 'Y_S', record=rec, dt=P['dt_ms'] * ms)

    bseed(seed)
    run(T_s * second)

    C     = np.asarray(S.C_async[:])
    YSint = np.asarray(S.YS_int[:] / (mole * second))
    YS_tr = np.asarray(monYS.Y_S / mmole)                 # (n_trace, nsteps) in mmole
    tgrid = np.asarray(monYS.t / second)
    # cross-check the in-equation integrator against an offline trapezoid (mole*s)
    off = trapezoid(YS_tr * 1e-3, tgrid, axis=1)
    xchk = float(np.max(np.abs(YSint[rec] - off)))
    nz_final = int(np.sum(np.asarray(S.Y_S[:] / mmole) > 0))
    return dict(C=C, YSint=YSint, YS_tr=YS_tr, tgrid=tgrid,
                xchk=xchk, nz_final=nz_final)


def compare_ensembles(rF, rB, Nsyn):
    """KS-test the FORMER vs BINV ensemble distributions of each observable."""
    print(f"\n--- PART B: async network on cpp_standalone, "
          f"FORMER vs BINV over {Nsyn} synapses ---")
    out = {}
    for name, a, b in [("C_async(T)", rF['C'], rB['C']),
                       ("int Y_S dt", rF['YSint'], rB['YSint'])]:
        ks, pv = stats.ks_2samp(a, b)
        ok = pv > 1e-3
        out[name] = ok
        print(f"  {name:<11s}: FORMER mean={a.mean():.4g} std={a.std():.3g} | "
              f"BINV mean={b.mean():.4g} std={b.std():.3g} | "
              f"KS p={pv:.3f}  {'PASS' if ok else 'FAIL'}")
    print(f"  in-equation int Y_S dt vs offline trapezoid: "
          f"FORMER max|d|={rF['xchk']:.1e}, BINV max|d|={rB['xchk']:.1e}")
    print(f"  Y_S(T) nonzero at endpoint (the DEGENERATE observable to avoid): "
          f"FORMER {rF['nz_final']}/{Nsyn}, BINV {rB['nz_final']}/{Nsyn}")
    print(f"PART B: {'PASS' if all(out.values()) else 'FAIL'}")
    return all(out.values())


